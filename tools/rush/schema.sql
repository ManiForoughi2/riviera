CREATE TABLE IF NOT EXISTS notes (id TEXT PRIMARY KEY, ig TEXT, thoughts TEXT, rating INTEGER DEFAULT 0, by TEXT, photo INTEGER DEFAULT 0, at INTEGER);
CREATE TABLE IF NOT EXISTS photos (id TEXT PRIMARY KEY, type TEXT, data BLOB);
CREATE TABLE IF NOT EXISTS ratings (pnm TEXT NOT NULL, brother TEXT NOT NULL, rating INTEGER DEFAULT 0, thoughts TEXT, at INTEGER, ig TEXT, frat INTEGER DEFAULT 0, priv INTEGER DEFAULT 0, PRIMARY KEY (pnm, brother));
CREATE INDEX IF NOT EXISTS ratings_at ON ratings(at);
CREATE INDEX IF NOT EXISTS notes_at ON notes(at);
CREATE TABLE IF NOT EXISTS added (n INTEGER PRIMARY KEY AUTOINCREMENT, first TEXT NOT NULL, last TEXT NOT NULL, grp INTEGER NOT NULL, brother TEXT, by TEXT, ig TEXT, at INTEGER);
CREATE INDEX IF NOT EXISTS added_at ON added(at);
